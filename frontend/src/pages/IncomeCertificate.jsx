import { useRef, useState } from "react";
import { DownloadSimple, FileText, Printer, Warning } from "@phosphor-icons/react";
import { useAuth } from "../auth/AuthContext";
import { Button, Card, Input, useToast } from "../components/ui";
import { isDemoMode } from "../mocks/data";
import { DemoNotice, Page } from "./shared";

function escapeHtml(value) {
  return String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
}

function demoCertificateHtml({ name, period, netIncome, verifiedIncome, verifiedShifts }) {
  const selfReported = Math.max(0, Number(netIncome) - Number(verifiedIncome));
  return `<!doctype html><html><head><meta charset="utf-8"><title>FairGig income certificate</title><style>body{margin:0;background:#eef3ef;font-family:Arial,sans-serif;color:#173129}.sheet{box-sizing:border-box;width:210mm;min-height:297mm;margin:0 auto;padding:25mm 22mm;background:#fff}.brand{font-size:22px;font-weight:800;color:#176b4f}.rule{height:2px;margin:18px 0 48px;background:#176b4f}h1{font-size:36px;margin:0 0 12px}p{line-height:1.6}.amount{margin:36px 0;padding:28px;background:#eef8f3}.amount span{display:block;color:#5a7067;font-size:13px}.amount strong{display:block;margin-top:8px;font-size:34px}.grid{display:grid;grid-template-columns:1fr 1fr;gap:20px;margin:30px 0}.grid div{border-top:1px solid #ccd9d3;padding-top:12px}.grid span{display:block;color:#5a7067;font-size:12px}.grid strong{display:block;margin-top:6px}table{width:100%;margin:32px 0;border-collapse:collapse}th,td{padding:12px;border-bottom:1px solid #ccd9d3;text-align:left}th{color:#5a7067;font-size:12px}.foot{margin-top:70px;color:#5a7067;font-size:12px}.sample{margin-top:24px;padding:12px;border:1px solid #895b0e;color:#895b0e}@media print{body{background:#fff}.sheet{margin:0}}</style></head><body><main class="sheet"><div class="brand">FairGig</div><div class="rule"></div><h1>Income certificate</h1><p>This development preview summarises self-reported and verified gig-work records for <strong>${escapeHtml(name)}</strong>.</p><section class="amount"><span>Net income for selected period</span><strong>PKR ${Number(netIncome).toLocaleString("en-PK")}</strong></section><section class="grid"><div><span>Period</span><strong>${escapeHtml(period)}</strong></div><div><span>Verified shifts</span><strong>${escapeHtml(verifiedShifts)}</strong></div><div><span>Verification status</span><strong>Mixed record</strong></div><div><span>Reference / QR</span><strong>Unavailable in Level 1</strong></div></section><table><thead><tr><th>Earnings type</th><th>Amount</th></tr></thead><tbody><tr><td>Verified income</td><td>PKR ${Number(verifiedIncome).toLocaleString("en-PK")}</td></tr><tr><td>Self-reported income</td><td>PKR ${selfReported.toLocaleString("en-PK")}</td></tr></tbody></table><p class="sample">Development sample only. This is not an official or persisted income certificate.</p><p class="foot">Generated by FairGig. Verification depends on the underlying shift review status.</p></main></body></html>`;
}

export default function IncomeCertificate() {
  const { user, api } = useAuth();
  const { notify } = useToast();
  const demo = isDemoMode();
  const frameRef = useRef(null);
  const [form, setForm] = useState(() => {
    const to = new Date();
    const from = new Date(to);
    from.setDate(from.getDate() - 89);
    return {
      from: from.toISOString().slice(0, 10),
      to: to.toISOString().slice(0, 10),
      period: "July to September 2026",
      netIncome: demo ? "194250" : "",
      verifiedIncome: demo ? "162400" : "",
      verifiedShifts: demo ? "41" : "",
    };
  });
  const [html, setHtml] = useState("");
  const [loading, setLoading] = useState(false);
  const [downloading, setDownloading] = useState(false);

  async function preview(event) {
    event.preventDefault();
    if (demo && (!form.period || !form.netIncome)) return notify("Enter a period and net income amount.", "error");
    if (!demo && (!form.from || !form.to || form.from > form.to)) return notify("Choose a valid date range.", "error");
    setLoading(true);
    try {
      let nextHtml;
      if (demo) {
        nextHtml = demoCertificateHtml({ name: user.name, ...form });
      } else {
        const summary = await api.get("certificate", `/certificates/income/summary?from=${form.from}&to=${form.to}`);
        const nextForm = {
          ...form,
          period: `${form.from} to ${form.to}`,
          netIncome: String(summary.total_net),
          verifiedIncome: String(summary.verified_net),
          verifiedShifts: String(summary.verified_shifts),
        };
        setForm(nextForm);
        nextHtml = await api.post("certificate", "/certificates/preview", {
          worker_id: user.id,
          worker_name: user.name,
          period: nextForm.period,
          gross: summary.total_gross,
          deductions: summary.total_deductions,
          net_income: summary.total_net,
          total_hours: summary.total_hours,
          verified_status: summary.verified_net > 0 ? "Partially or fully verified" : "Worker reported",
        });
      }
      setHtml(nextHtml);
      notify(demo ? "Development sample preview created." : "Certificate preview created.", "success");
    } catch (error) {
      notify(error.message, "error");
    } finally {
      setLoading(false);
    }
  }

  async function downloadCertificate() {
    setDownloading(true);
    try {
      const blob = await api.download("certificate", `/certificates/income?from=${form.from}&to=${form.to}`);
      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = url;
      link.download = `FairGig-Income-${form.from}_${form.to}.pdf`;
      link.click();
      URL.revokeObjectURL(url);
    } catch (error) {
      notify(error.message, "error");
    } finally {
      setDownloading(false);
    }
  }

  function printCertificate() {
    const frameWindow = frameRef.current?.contentWindow;
    if (!frameWindow) return;
    frameWindow.focus();
    frameWindow.print();
  }

  return (
    <Page eyebrow="Portable income record" title="Income certificate" description="Create a print-friendly summary for documentation, applications, or your own records." action={html && <div className="button-row"><Button type="button" variant="secondary" onClick={printCertificate}><Printer size={18} />Print preview</Button>{!demo && <Button type="button" onClick={downloadCertificate} loading={downloading}><DownloadSimple size={18} />Download PDF</Button>}</div>}>
      {demo && <DemoNotice />}
      <div className="two-column certificate-layout">
        <Card>
          <div className="section-head"><div><h2>Certificate details</h2><p>The preview uses your signed-in account name.</p></div></div>
          <form className="certificate-form" onSubmit={preview}>
            <Input label="Worker name" name="worker_name" value={user.name} readOnly />
            {demo ? <Input label="Period" name="period" value={form.period} onChange={(event) => setForm({ ...form, period: event.target.value })} placeholder="July to September 2026" /> : <><Input label="From" name="from" type="date" value={form.from} onChange={(event) => setForm({ ...form, from: event.target.value })} /><Input label="To" name="to" type="date" value={form.to} onChange={(event) => setForm({ ...form, to: event.target.value })} /></>}
            <Input label="Net income (PKR)" name="net_income" type="number" min="0" value={form.netIncome} readOnly={!demo} onChange={(event) => setForm({ ...form, netIncome: event.target.value })} hint={demo ? undefined : "Calculated from persisted shifts."} />
            <Input label="Verified income (PKR)" name="verified_income" type="number" min="0" max={form.netIncome || undefined} value={form.verifiedIncome} readOnly={!demo} onChange={(event) => setForm({ ...form, verifiedIncome: event.target.value })} hint="The remainder is shown as worker-reported." />
            <Input label="Verified shifts" name="verified_shifts" type="number" min="0" value={form.verifiedShifts} readOnly={!demo} onChange={(event) => setForm({ ...form, verifiedShifts: event.target.value })} />
            <Button type="submit" loading={loading}><FileText size={18} />Generate preview</Button>
          </form>
          <div className="data-note certificate-note"><Warning size={18} /><span>{demo ? "Development mode uses labeled sample totals." : "Income totals are calculated from your persisted shifts. Verification applies only to records marked confirmed; a public verification URL and QR code are not available yet."}</span></div>
        </Card>
        <Card className="certificate-placeholder">
          <FileText size={42} />
          <h2>A4 preview</h2>
          <p>Generate the certificate to inspect its print layout.</p>
          <ul><li>Signed-in worker identity</li><li>Selected reporting period</li><li>Verified shift count</li><li>Clear verification disclaimer</li></ul>
        </Card>
      </div>
      {html && <section className="page-section certificate-preview-wrap"><div className="section-head"><div><h2>Print preview</h2><p>A4 HTML returned by the certificate service.</p></div></div><div className="certificate-breakdown" aria-label="Earnings breakdown entered for preview"><div><span>Verified income</span><strong>PKR {Number(form.verifiedIncome || 0).toLocaleString("en-PK")}</strong></div><div><span>Self-reported income</span><strong>PKR {Math.max(0, Number(form.netIncome || 0) - Number(form.verifiedIncome || 0)).toLocaleString("en-PK")}</strong></div><div><span>Certificate reference</span><strong>Not provided</strong></div><div><span>QR verification</span><strong>Not available</strong></div></div><iframe ref={frameRef} className="certificate-frame" title="Income certificate preview" srcDoc={html} sandbox="allow-same-origin" /></section>}
    </Page>
  );
}
