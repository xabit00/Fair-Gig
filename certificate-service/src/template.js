function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function renderCertificate(data) {
  const workerName = escapeHtml(data.name || data.worker_name || "FairGig Worker");
  const workerId = escapeHtml(data.worker_id || "Not supplied");
  const period = escapeHtml(data.period || "Demo period");
  const gross = Number(data.gross !== undefined ? data.gross : (data.total_gross || 0)).toLocaleString("en-PK", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  const deductions = Number(data.deductions !== undefined ? data.deductions : (data.total_deductions || 0)).toLocaleString("en-PK", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  const net = Number(data.net !== undefined ? data.net : (data.net_income || data.total_net || 0)).toLocaleString("en-PK", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  const hours = Number(data.hours !== undefined ? data.hours : (data.total_hours || 0)).toFixed(1);
  const verifiedStatus = escapeHtml(data.verified_status || "Documented");
  const generatedDate = escapeHtml(
    data.generated_at
      ? new Date(data.generated_at).toLocaleDateString("en-PK", {
          year: "numeric",
          month: "long",
          day: "numeric",
        })
      : new Date().toLocaleDateString("en-PK", {
          year: "numeric",
          month: "long",
          day: "numeric",
        })
  );

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>FairGig Income Certificate</title>
  <style>
    :root { color-scheme: light; font-family: Arial, sans-serif; color: #17342b; }
    body { margin: 0; background: #eef3f0; }
    main { box-sizing: border-box; width: 210mm; min-height: 297mm; margin: 24px auto; padding: 24mm; background: #fff; border-top: 8px solid #187453; }
    header { display: flex; justify-content: space-between; align-items: start; border-bottom: 1px solid #cbd8d2; padding-bottom: 24px; }
    h1 { margin: 0; font-size: 28px; letter-spacing: -0.5px; }
    .brand { color: #187453; font-weight: 800; font-size: 20px; }
    .lede { margin: 36px 0; line-height: 1.65; color: #40564e; }
    dl { display: grid; grid-template-columns: 1fr 1fr; gap: 22px; margin: 0; }
    dt { margin-bottom: 6px; color: #667b73; font-size: 12px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.08em; }
    dd { margin: 0; font-size: 18px; font-weight: 700; }
    footer { margin-top: 70px; padding-top: 20px; border-top: 1px solid #cbd8d2; color: #667b73; font-size: 12px; line-height: 1.5; }
    @page { size: A4; margin: 0; }
    @media print { body { background: #fff; } main { margin: 0; } }
  </style>
</head>
<body>
  <main>
    <header><div><div class="brand">FairGig</div><h1>Income Certificate</h1></div><strong>${generatedDate}</strong></header>
    <p class="lede">This document summarizes documented income records supplied to FairGig for the stated period.</p>
    <dl>
      <div><dt>Worker</dt><dd>${workerName}</dd></div>
      <div><dt>Worker ID</dt><dd>${workerId}</dd></div>
      <div><dt>Reporting period</dt><dd>${period}</dd></div>
      <div><dt>Total Hours</dt><dd>${hours} hrs</dd></div>
      <div><dt>Gross Income</dt><dd>PKR ${gross}</dd></div>
      <div><dt>Deductions</dt><dd>PKR ${deductions}</dd></div>
      <div><dt>Net Income</dt><dd>PKR ${net}</dd></div>
      <div><dt>Verification Status</dt><dd>${verifiedStatus}</dd></div>
    </dl>
    <footer>Generated by FairGig Income Certificate Service. All values are calculated from logged shift records.</footer>
  </main>
</body>
</html>`;
}

module.exports = renderCertificate;
